#!/usr/bin/env node
// V2.0.1 — content-hashed CSS cache-busting.
//
// Runs after `tailwindcss` has compiled the raw stylesheet to the fixed
// temp path below (see package.json's "css:build"/"css:hash" scripts).
// This script:
//   1. Reads that raw compiled CSS.
//   2. Derives a deterministic filename from its content (sha256, first
//      10 hex chars) — identical CSS always produces the same filename;
//      any change to the CSS produces a new one.
//   3. Removes any previously generated `public/styles.*.css` (including
//      the old unversioned `public/styles.css`) so repeated local builds
//      never accumulate stale hashed files — `public/` isn't cleaned
//      between builds the way `dist/` is.
//   4. Writes the hashed file into `public/`, which Astro copies verbatim
//      into `dist/` for both `astro dev` and `astro build`.
//   5. (Re)writes `src/generated/styles-manifest.ts`, a tiny generated
//      module exporting the href BaseLayout links to — so the hashed
//      name is known at Astro build time without any manual editing.
//
// Nothing here touches Tailwind itself or how global.css is compiled —
// see astro.config.mjs for why the CLI output stays outside the Astro/
// Vite module graph entirely.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const RAW_CSS_PATH = join(ROOT, '.tmp', 'tailwind-output.css');
const PUBLIC_DIR = join(ROOT, 'public');
const GENERATED_DIR = join(ROOT, 'src', 'generated');
const MANIFEST_PATH = join(GENERATED_DIR, 'styles-manifest.ts');

if (!existsSync(RAW_CSS_PATH)) {
  console.error(`hash-css: ${RAW_CSS_PATH} not found — run "npm run css:build" first.`);
  process.exit(1);
}

const css = readFileSync(RAW_CSS_PATH, 'utf-8');
if (css.trim().length === 0) {
  console.error('hash-css: compiled CSS is empty — refusing to publish an empty stylesheet.');
  process.exit(1);
}

const hash = createHash('sha256').update(css).digest('hex').slice(0, 10);
const filename = `styles.${hash}.css`;

// Clean stale locally-generated hashed stylesheets (and the legacy
// unversioned styles.css, if still present from before this hotfix) so
// they never accumulate in public/ across repeated local builds.
if (existsSync(PUBLIC_DIR)) {
  for (const entry of readdirSync(PUBLIC_DIR)) {
    if (entry === filename) continue;
    if (/^styles\.[0-9a-f]{10}\.css$/.test(entry) || entry === 'styles.css') {
      unlinkSync(join(PUBLIC_DIR, entry));
    }
  }
} else {
  mkdirSync(PUBLIC_DIR, { recursive: true });
}

writeFileSync(join(PUBLIC_DIR, filename), css);

mkdirSync(GENERATED_DIR, { recursive: true });
writeFileSync(
  MANIFEST_PATH,
  `// Auto-generated by scripts/hash-css.mjs — do not edit by hand.\n` +
    `// Regenerated on every "npm run dev" / "npm run build".\n` +
    `export const STYLES_HREF = '/${filename}';\n`,
);

console.log(`hash-css: ${filename} (${css.length.toLocaleString()} bytes, sha256:${hash})`);
